def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--tk-only", action="store_true",
                        help="只构建 tkinter 版（跳过 Toga 版）")
    parser.add_argument("--skip-verify", action="store_true")
    parser.add_argument("--no-art", action="store_true",
                        help="不打包第三方美术资源（用于需要干净授权的构建）")
    parser.add_argument("--no-ocr", action="store_true",
                        help="不打包可选 OCR 引擎（winsdk 约 11 MB；磁盘紧张时用）")
    args = parser.parse_args(argv)

    if args.no_art:
        # The flag must reach the specs, which import spec_common at build time.
        os.environ["RECNEKO_NO_ART"] = "1"
    if args.no_ocr:
        os.environ["RECNEKO_NO_OCR"] = "1"

    DIST.mkdir(parents=True, exist_ok=True)
    BUILD.mkdir(parents=True, exist_ok=True)
    clean_dist()
    prepare_data()

    results: list[str] = []

    # ---- 1. tkinter single file (PRIMARY) --------------------------------
    write_buildcfg("tk")
    if run_pyinstaller(TK_ONEFILE_SPEC, "tk-onefile") != 0:
        return 1
    tk_exe = DIST / f"{APP_NAME}.exe"
    if not tk_exe.is_file():
        print(f"[build] 主交付物 {tk_exe.name} 未生成")
        return 1
    results.append(f"单文件 exe   : {tk_exe.name}  {human(tk_exe.stat().st_size)}")

    # ---- 2. tkinter folder ----------------------------------------------
    if run_pyinstaller(TK_ONEDIR_SPEC, "tk-onedir") != 0:
        return 1
    folder = DIST / APP_NAME
    if not (folder / f"{APP_NAME}.exe").is_file():
        print(f"[build] 目录版缺少 {APP_NAME}.exe")
        return 1
    results.append(f"目录版       : {folder.name}/  {human(folder_size(folder))}")

    archive = zip_folder(folder, DIST / f"{APP_NAME}-portable.zip")
    if archive:
        results.append(f"便携压缩包   : {archive.name}  {human(archive.stat().st_size)}")

    # ---- 3. verification (while _buildcfg still says tkinter) ------------
    # The self test bundles _buildcfg, so it must run while the tkinter value is
    # in place - otherwise it reports whatever the last build wrote, which is
    # how an earlier revision ended up testing a "toga" config.
    if not args.skip_verify:
        if not verify_frozen():
            print("\n[build] 冻结自检失败：打包结果不可用")
            return 1
        results.append("冻结自检     : 通过")

    # ---- 4. Toga build (x64 only) ---------------------------------------
    has_toga = False
    if not args.tk_only:
        write_buildcfg("toga")
        if run_pyinstaller(TOGA_ONEFILE_SPEC, "toga-onefile") == 0:
            toga_exe = DIST / f"{TOGA_NAME}.exe"
            if toga_exe.is_file():
                has_toga = True
                results.append(
                    f"Toga 版      : {toga_exe.name}  {human(toga_exe.stat().st_size)}"
                    "（仅 x64 可用）"
                )
        else:
            print("[build] Toga 版构建失败（不影响主交付物）")

    # ---- 5. generated instructions --------------------------------------
    info = write_instructions(has_toga, args.no_art)
    results.append(f"使用说明     : {info.name}")

    # ---- 6. assert the primary deliverables survived --------------------
    if not tk_exe.is_file() or not (folder / f"{APP_NAME}.exe").is_file():
        print("\n[build] 严重错误：主交付物在构建结束时不存在")
        return 1

    # ---- 7. leave the tree in its neutral state -------------------------
    # _buildcfg.py is a build artifact; committing "toga" would make a later
    # manual `pyinstaller MiRecoveryHelper-tk.spec` prefer a backend it does not
    # contain.
    write_buildcfg(None)

    print("\n构建完成：")
    for line in results:
        print(f"  {line}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
