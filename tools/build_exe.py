#!/usr/bin/env python3
"""Build every Windows deliverable and verify each one actually starts.

Produces, in ``dist/``:

  * ``rec检查喵.exe``                 tkinter, single file (primary)
  * ``rec检查喵/``                    tkinter, folder - nothing unpacked at startup
  * ``rec检查喵-portable.zip``        the folder, zipped for handing over
  * ``rec检查喵-toga.exe``            Toga build (x64 Windows only)
  * ``使用说明.txt``                  generated from the real artifact names

Design notes
------------
* **No renaming after the fact.** Each spec names its own output, so the tkinter
  build can no longer be clobbered by the Toga build writing the same filename.
  An earlier version built both as ``MiRecoveryHelper.exe`` and renamed
  afterwards, which silently destroyed the primary deliverable when the build
  order changed.
* **Instructions are generated**, not hand-written, so they cannot describe a
  layout that no longer exists. (They did: the shipped text told users to run
  ``MiRecoveryHelper\\MiRecoveryHelper.exe`` after both names had changed.)
* **``_buildcfg`` is written before building** so the frozen app knows which GUI
  it was built for. Setting an environment variable inside a spec, as an earlier
  version did, has no effect on the built executable.

Usage
-----
    python tools/build_exe.py              # everything + self test
    python tools/build_exe.py --tk-only
    python tools/build_exe.py --no-art     # build without third-party artwork
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
DIST = PROJECT_ROOT / "dist"
BUILD = PROJECT_ROOT / "build"
VENV_PYTHON = PROJECT_ROOT / ".venv" / "Scripts" / "python.exe"

sys.path.insert(0, str(PROJECT_ROOT / "src"))
from mirecovery import theme  # noqa: E402
from mirecovery.logsetup import log_directory  # noqa: E402

TK_ONEFILE_SPEC = "MiRecoveryHelper-tk.spec"
TK_ONEDIR_SPEC = "MiRecoveryHelper-tk.onedir.spec"
TOGA_ONEFILE_SPEC = "MiRecoveryHelper.spec"
SELFTEST_SPEC = "MiRecoveryHelper.selftest.spec"

APP_NAME = theme.EXE_BASENAME                 # rec检查喵
TOGA_NAME = f"{APP_NAME}-toga"
SELFTEST_NAME = f"{APP_NAME}-selftest"

# Only artifacts this script owns may be deleted from dist/.
MANAGED_ARTIFACTS = (
    f"{APP_NAME}.exe",
    f"{TOGA_NAME}.exe",
    f"{SELFTEST_NAME}.exe",
    SELFTEST_NAME,
    f"{APP_NAME}-portable.zip",
    APP_NAME,
    "使用说明.txt",
    # Names from earlier revisions, removed so stale builds cannot be mistaken
    # for current ones.
    "MiRecoveryHelper.exe",
    "MiRecoveryHelper-toga.exe",
    "MiRecoveryHelperSelfTest.exe",
    "MiRecoveryHelper-portable.zip",
    "MiRecoveryHelper",
)


def python_executable() -> str:
    if VENV_PYTHON.is_file():
        return str(VENV_PYTHON)
    return sys.executable


def run_pyinstaller(spec: str, workpath: str) -> int:
    command = [
        python_executable(), "-m", "PyInstaller",
        "--noconfirm", "--clean",
        "--distpath", str(DIST),
        "--workpath", str(BUILD / workpath),
        str(PROJECT_ROOT / spec),
    ]
    print(f"[build] {spec}")
    result = subprocess.run(command, cwd=PROJECT_ROOT)
    if result.returncode != 0:
        print(f"[build] {spec} 失败（退出码 {result.returncode}）")
    return result.returncode


def write_buildcfg(gui: str | None) -> None:
    """Record the intended GUI so the frozen app prefers it at startup."""
    target = PROJECT_ROOT / "src" / "mirecovery" / "_buildcfg.py"
    literal = f'"{gui}"' if gui else "None"
    target.write_text(
        '"""Build-time GUI preference (generated by tools/build_exe.py).\n\n'
        "Do not edit by hand - it is overwritten on every build. The committed\n"
        "value is None, meaning auto-detect at runtime.\n"
        '"""\n\n'
        "from __future__ import annotations\n\n"
        '# "tk", "toga" or None (auto-detect at runtime).\n'
        f"DEFAULT_GUI: str | None = {literal}\n",
        encoding="utf-8",
    )
    print(f"[build] _buildcfg.DEFAULT_GUI = {literal}")


def clean_dist() -> None:
    """Remove only artifacts this script owns."""
    for name in MANAGED_ARTIFACTS:
        target = DIST / name
        if target.is_dir():
            shutil.rmtree(target, ignore_errors=True)
        elif target.is_file():
            target.unlink()


def prepare_data() -> None:
    """Regenerate kb.json and image_refs.json so the build is never stale."""
    for script in ("build_kb.py", "build_references.py"):
        result = subprocess.run(
            [python_executable(), str(PROJECT_ROOT / "tools" / script)],
            cwd=PROJECT_ROOT,
        )
        if result.returncode != 0:
            raise SystemExit(f"{script} 失败，构建中止")


def verify_frozen() -> bool:
    print("[verify] 冻结自检")
    if run_pyinstaller(SELFTEST_SPEC, "selftest") != 0:
        return False

    # onedir: no runtime extraction, so this works even when %TEMP% is tight.
    self_test = DIST / f"{SELFTEST_NAME}" / f"{SELFTEST_NAME}.exe"
    if not self_test.is_file():
        print(f"[verify] 找不到自检程序：{self_test}")
        return False

    # Keep any incidental temp use inside the project.
    env = dict(os.environ)
    scratch = BUILD / "run-tmp"
    scratch.mkdir(parents=True, exist_ok=True)
    env["TEMP"] = env["TMP"] = str(scratch)

    result = subprocess.run(
        [str(self_test)],
        cwd=PROJECT_ROOT,
        capture_output=True,
        text=True,
        # The self test emits UTF-8 (it reconfigures its own streams, because the
        # console here is GBK and cannot encode the UI's ✅/❌). Decoding its output
        # with the locale codec mangled it, so the build reported "self test
        # failed" while the test itself had printed SELFTEST OK.
        encoding="utf-8",
        errors="replace",
        env=env,
    )
    output = (result.stdout or "") + (result.stderr or "")
    print(output.strip())
    return result.returncode == 0 and "SELFTEST OK" in output


def zip_folder(folder: Path, archive: Path) -> Path | None:
    if not folder.is_dir():
        return None
    if archive.is_file():
        archive.unlink()
    with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as handle:
        for path in sorted(folder.rglob("*")):
            if path.is_file():
                handle.write(path, path.relative_to(DIST))
    return archive


def human(size: int) -> str:
    return f"{size / 1024 / 1024:.1f} MB"


def folder_size(folder: Path) -> int:
    return sum(p.stat().st_size for p in folder.rglob("*") if p.is_file())


